#!/usr/bin/env python3
"""One genuine US->French V2V voice naturalness test.

Existing 15.04-second VIDEO ONLY comes from previous successful LTX V2V GitHub
artifact 40899629965. New French voice is generated by explicitly selected
Chatterbox Multilingual V3; keep its natural pace. Once length checks pass, the
existing TBDub Student renders the lip movements driven by that precise voice.

No new V2V/LTX, no artificial TTS slowing, no voice cloning, no publication.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path.cwd()))
ROOT=Path("productions/US-FR-V2V-REAL-20261029")
OUT=ROOT/"CHATTERBOX_V3_TBDUB_15S"
SOURCE=ROOT/"EXISTING_V2V_15S"
OUT.mkdir(parents=True,exist_ok=True)

SCRIPT_FR = (
    "Vous savez comment automatiser ChatGPT ? Regardez. "
    "Un fichier arrive sur Dropbox, et le Zap démarre automatiquement. "
    "Plus besoin de répéter les mêmes gestes chaque jour. "
    "Vous configurez une fois, et ça tourne tout seul. "
    "C'est pratique, et même un débutant peut le faire."
)

def sh(parts:list[str],limit=180) -> str:
    proc=subprocess.run(parts,capture_output=True,text=True,timeout=limit)
    if proc.returncode:
        raise RuntimeError("Command failed: "+str(parts[:5])+" "+(proc.stdout+proc.stderr)[-2500:])
    return proc.stdout

def probe(file:Path) -> dict:
    return json.loads(sh(["ffprobe","-v","error","-show_streams",
                          "-show_format","-of","json",str(file)]))

def duration(file:Path) -> float:
    return float(probe(file)["format"]["duration"])

def record(file:str,data:dict) -> None:
    (OUT/file).write_text(json.dumps(data,ensure_ascii=False,indent=2)+"\n",encoding="utf-8")

def digest(file:Path) -> str:
    return hashlib.sha256(file.read_bytes()).hexdigest()

def get_original():
    """Use LTX transformed MP4 from 2026-10-29 *as is*, strip previous dubbed audio."""
    path=SOURCE/"fr-v2v-raw-15s.mp4"
    if not path.is_file() or path.stat().st_size<1_000_000:
        raise RuntimeError("Missing authentic 15s transformed V2V from GitHub run 40899629965")
    state=probe(path)
    vid=next((x for x in state["streams"] if x["codec_type"]=="video"),None)
    if not vid or (vid["width"],vid["height"])!=(1344,768):
        raise RuntimeError("Unexpected original V2V dimensions")
    if not 15.0 < duration(path) < 15.15:
        raise RuntimeError("Original V2V must remain the genuine 15-second result")
    original=OUT/"original_v2v_15s.mp4"
    sh(["ffmpeg","-y","-v","error","-i",str(path),"-map","0:v:0",
        "-an","-c:v","copy","-movflags","+faststart",str(original)])
    record("provenance.json",{
        "original_run":40899629965,
        "original_artifact":"US-FR-REAL-V2V-15S-40899629965",
        "original_file":"fr-v2v-raw-15s.mp4",
        "original_sha256":digest(path),
        "no_v2v_rerender":True,
        "original_input_is_audio_free":True,
        "script_fr":SCRIPT_FR,
    })
    print("AUTHENTIC_EXISTING_V2V_15S_READY",flush=True)

def generate_voice():
    import modal
    from deploy import modal_chatterbox_v3_fr_pilot as ch
    if os.getenv("STUDIO_MODAL_WORKSPACE")!="lucj76861":
        raise RuntimeError("Wrong Modal workspace")
    if os.getenv("CONFIRM_ONE_VOICE_GPU")!="YES" or os.getenv("GITHUB_RUN_ATTEMPT","1")!="1":
        raise RuntimeError("One voice GPU authorization missing")
    if not (OUT/"original_v2v_15s.mp4").is_file():
        raise RuntimeError("No video provenance")
    record("status.json",{"step":"CHATTTERBOX_V3_GPU_STARTED"})
    try:
        with ch.app.run(name="ugcv2-chatterbox-v3-french-ab",environment_name="main"):
            result=ch.render_french_v3_candidates.remote(SCRIPT_FR)
        candidates=[]
        for entry in result["candidates"]:
            name=entry["label"]+".wav"
            file=OUT/name
            file.write_bytes(base64.b64decode(entry["audio_b64"],validate=True))
            if digest(file)!=entry["sha256"]:
                raise RuntimeError("Audio checksum mismatch")
            d=duration(file)
            candidates.append({"label":entry["label"],"filename":name,
                               "duration":d,"parameters":entry["parameters"],
                               "sha256":entry["sha256"]})
        # Select a natural-paced complete take, no atempo/phase-vocoder retiming.
        viable=[x for x in candidates if 10.8<=x["duration"]<=14.85]
        if not viable:
            record("voice_candidates.json",{
                "engine":result["engine"],"v3_explicit":result["v3_explicit"],
                "candidates":candidates,
                "decision":"No complete 11-15s voice with original timing; GPU lipsync blocked",
            })
            raise RuntimeError("Chatterbox voice did not fit the 15s source naturally")
        preferred=min(viable,key=lambda x:abs(x["duration"]-13.4))
        wav=OUT/preferred["filename"]
        target=round(min(15.0, max(11.0, preferred["duration"]+0.22)),2)
        finalwav=OUT/"voice_french_v3_selected.wav"
        sh(["ffmpeg","-y","-v","error","-i",str(wav),
            "-af",f"apad,atrim=duration={target}",
            "-ar","16000","-ac","1","-c:a","pcm_s16le",str(finalwav)])
        video=OUT/"original_v2v_for_tbdub.mp4"
        sh(["ffmpeg","-y","-v","error","-i",str(OUT/"original_v2v_15s.mp4"),
            "-t",str(target),"-map","0:v:0","-vf","fps=25,format=yuv420p",
            "-an","-c:v","libx264","-crf","18","-preset","fast",
            "-movflags","+faststart",str(video)])
        if abs(duration(video)-target)>.10 or abs(duration(finalwav)-target)>.10:
            raise RuntimeError("Chosen voice/video durations do not match")
        record("voice_candidates.json",{
            "engine":result["engine"],"v3_explicit":result["v3_explicit"],
            "model_revision":result["model_revision"],
            "speaker":result["speaker"],"script_fr":SCRIPT_FR,
            "candidates":candidates,"selected":preferred,
            "duration_for_TBDub_seconds":target,
            "time_stretch_applied":False,"no_voice_clone":True,
            "audio_sha256":digest(finalwav),
            "listening_review":"REQUIRED — code cannot rate human naturalness",
        })
        record("status.json",{"step":"V3_VOICE_GENERATED_REQUIRES_LISTENING",
                             "selected":preferred["label"],"duration":target})
        print("NATIVE_PACED_CHATTERBOX_V3_FRENCH_VOICE_READY",target,flush=True)
    except BaseException as err:
        record("status.json",{"step":"VOICE_FAILED_NO_TBDUB_GPU","error":str(err)[-2800:]})
        raise

def lipsync():
    if os.getenv("CONFIRM_ONE_TBDUB_GPU")!="YES" or os.getenv("GITHUB_RUN_ATTEMPT","1")!="1":
        raise RuntimeError("One TBDub GPU authorization missing")
    voice=OUT/"voice_french_v3_selected.wav"
    video=OUT/"original_v2v_for_tbdub.mp4"
    if not voice.is_file() or not video.is_file():
        raise RuntimeError("French voice must exist before any TBDub GPU")
    d=duration(voice)
    if not 11.0<=d<=15.0 or abs(duration(video)-d)>.10:
        raise RuntimeError("No naturally paced 11-15s audio/video match")
    import modal
    from deploy import modal_tbdub_fr_worker as tbdub
    vidb=base64.b64encode(video.read_bytes()).decode()
    audiob=base64.b64encode(voice.read_bytes()).decode()
    with tbdub.app.run(name="ugcv2-fr-v3-tbdub-fifteen-second-pilot",environment_name="main"):
        try:
            preflight=tbdub.preflight.remote(vidb,audiob)
            if preflight.get("status")!="CPU_FACE_PREFLIGHT_PASSED":
                raise RuntimeError("TBDub Mediapipe tracking failed")
            (OUT/"tbdub_face_preflight_crop.mp4").write_bytes(
                base64.b64decode(preflight.pop("preview_base64"),validate=True))
            record("tbdub_preflight.json",preflight)
        except BaseException as err:
            record("status.json",{"step":"TBDUB_CPU_FACE_PREFLIGHT_FAILED_NO_GPU",
                                  "error":str(err)[-3600:]})
            raise
        try:
            prepared=tbdub.prepare_student_only.remote()
            if prepared.get("status")!="STUDENT_WEIGHTS_READY":
                raise RuntimeError("Official TBDub Student model cache incomplete")
            record("tbdub_checkpoint_cache.json",{
                "status":prepared["status"],
                "model":prepared["model"],
                "seconds":prepared["seconds"],
                "all_present":prepared["all_present"],
            })
        except BaseException as err:
            record("status.json",{"step":"TBDUB_CPU_WEIGHTS_NOT_READY_NO_GPU",
                                  "error":str(err)[-3600:]})
            raise
        record("status.json",{"step":"TBDUB_15S_GPU_STARTED","voice_s":d})
        try:
            result=tbdub.render_student_french_twelve_to_fifteen_seconds.remote(vidb,audiob)
            if result["metadata"]["status"]!="ACTUAL_TBDUB_OUTPUT_HUMAN_REVIEW_REQUIRED":
                raise RuntimeError("TBDub returned unexpected rendering status")
            generated=OUT/"tbdub_v3_raw.mp4"
            generated.write_bytes(base64.b64decode(result["video_base64"],validate=True))
            if digest(generated)!=result["metadata"]["video_sha256"]:
                raise RuntimeError("TBDub generated video checksum mismatch")
            record("tbdub_render_metadata.json",result["metadata"])
        except BaseException as err:
            record("status.json",{"step":"TBDUB_GPU_FAILED_NO_FINAL_MP4",
                                  "error":str(err)[-4600:]})
            raise
    print("ACTUAL_TBDUB_FRENCH_LIPSYNC_VIDEO_RENDERED",flush=True)

def finish():
    raw=OUT/"tbdub_v3_raw.mp4"
    wav=OUT/"voice_french_v3_selected.wav"
    original=OUT/"original_v2v_for_tbdub.mp4"
    if not raw.is_file() or not wav.is_file():
        raise RuntimeError("Missing true TBDub render or voice. No fake MP4.")
    target=duration(wav)
    if abs(duration(raw)-target)>.8:
        raise RuntimeError(f"TBDub duration mismatch: rendered={duration(raw)},voice={target}")
    final=OUT/"UGCv2_FR_ChatterboxV3_TBDub_15s_A_VERIFIER.mp4"
    sh(["ffmpeg","-y","-v","error","-i",str(raw),"-i",str(wav),
        "-map","0:v:0","-map","1:a:0","-t",str(target),
        "-vf","fps=25,scale=1344:768:flags=lanczos,format=yuv420p",
        "-c:v","libx264","-crf","18","-preset","fast",
        "-c:a","aac","-b:a","192k","-ar","48000",
        "-movflags","+faststart",str(final)],limit=360)
    sh(["ffmpeg","-v","error","-xerror","-i",str(final),"-f","null","-"],limit=240)
    parsed=probe(final)
    types={x["codec_type"] for x in parsed["streams"]}
    fdur=float(parsed["format"]["duration"])
    if not {"audio","video"}.issubset(types) or not 11.0<=fdur<=15.1:
        raise RuntimeError("Incomplete final French MP4")
    comparison=OUT/"UGCv2_FR_ChatterboxV3_TBDub_AVANT_APRES.mp4"
    sh(["ffmpeg","-y","-v","error","-i",str(original),"-i",str(final),
        "-filter_complex",
        "[0:v]fps=25,scale=672:384[v0];[1:v]fps=25,scale=672:384[v1];"
        "[v0][v1]hstack=inputs=2[v]",
        "-map","[v]","-map","1:a:0","-t",str(target),
        "-c:v","libx264","-preset","fast","-crf","20",
        "-pix_fmt","yuv420p","-c:a","aac",
        "-movflags","+faststart",str(comparison)],limit=360)
    for label,clip in [("before",original),("after",final)]:
        sh(["ffmpeg","-y","-v","error","-i",str(clip),
            "-vf","fps=1,scale=336:192,tile=4x3",
            "-frames:v","1",str(OUT/(label+"_contact.jpg"))],limit=180)
    record("status.json",{
        "step":"REAL_V3_TBDUB_MP4_RENDERED_PENDING_HUMAN_REVIEW",
        "final_file":final.name,"compare_file":comparison.name,
        "video_seconds":fdur,"sha256":digest(final),
        "v3_voice_slowness_fixed_by_speed_change":False,
        "original_V2V_unchanged":True,
        "human_checks":["French voice naturalness", "speaking pace",
                        "teeth/face geometry", "mouth-to-voice timing"],
    })
    print("NEW_FRENCH_TUTORIAL_15S_MP4_READY",final,flush=True)


if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("phase",choices=["source","voice","lipsync","finish"])
    phase=p.parse_args().phase
    {"source":get_original,"voice":generate_voice,
     "lipsync":lipsync,"finish":finish}[phase]()
